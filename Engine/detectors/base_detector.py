from abc import ABC, abstractmethod
from typing import List, Dict, Any, Optional


class BaseBugDetector(ABC):
    """Abstract Base Class for all SQL Bug Detectors.
    
    Enables a plug-and-play enterprise architecture where new bug detectors 
    can be added infinitely without modifying the core engine code.
    Fully flexible with backward compatibility for all team members' plugins.
    """

    @abstractmethod
    def detect(self, parsed_steps: List[Dict[str, Any]], step_trace: List[Dict[str, Any]], db_connection: Any = None, *args, **kwargs) -> Optional[Dict[str, Any]]:
        """Analyzes query steps and execution data to find anomalies.

        Args:
            parsed_steps: The structured steps generated by the parser.
            step_trace: The execution results, metrics, and timings from DuckDB.
            db_connection: Active database connection for deep-dive queries if needed.
            
        Returns:
            A bug report dictionary if an anomaly is found, or None otherwise.
        """
        pass

    def _format_bug_report(self, bug_type: str, severity: str, description: str) -> Dict[str, Any]:
        """Helper utility for consistent, standardized bug report formatting 
        across all detectors in the Echo Engine.
        """
        return {
            "bug_type": bug_type,
            "severity": severity,
            "description": description,
        }